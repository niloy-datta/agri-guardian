"""Migration chain tests.

The `migrated_database` fixture drops every application schema and runs
`alembic upgrade head` against an empty PostgreSQL/PostGIS, so reaching
these assertions at all means the clean-database upgrade succeeded. What
is asserted here is what the upgrade actually produced.

The autogenerate check is the load-bearing one: it proves the hand-written
migrations still describe the same schema as the SQLAlchemy models, which
is the failure mode that otherwise surfaces in production as a missing
column.
"""

import sqlalchemy
from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected

from tests.conftest import BACKEND_API_ROOT

EXPECTED_TABLES = {
    ("identity", "users"),
    ("identity", "profiles"),
    ("identity", "roles"),
    ("identity", "user_roles"),
    ("farm", "farmer_profiles"),
    ("farm", "fields"),
    ("farm", "crop_cycles"),
    ("commerce", "buyer_profiles"),
    ("commerce", "listings"),
    ("commerce", "bids"),
    ("commerce", "orders"),
    ("commerce", "inventory_reservations"),
    ("commerce", "order_events"),
    ("platform", "outbox_events"),
    ("platform", "audit_logs"),
    ("platform", "idempotency_keys"),
}

EXPECTED_SCHEMAS = {
    "identity",
    "farm",
    "intelligence",
    "commerce",
    "circular",
    "operations",
    "platform",
}


def _alembic_config() -> Config:
    config = Config(str(BACKEND_API_ROOT / "alembic.ini"))
    config.set_main_option("script_location", str(BACKEND_API_ROOT / "alembic"))
    return config


def test_all_schemas_exist(migrated_database: sqlalchemy.Engine) -> None:
    with migrated_database.connect() as connection:
        rows = connection.execute(
            sqlalchemy.text("SELECT schema_name FROM information_schema.schemata")
        )
        present = {row[0] for row in rows}
    assert EXPECTED_SCHEMAS.issubset(present)


def test_required_extensions_are_installed(
    migrated_database: sqlalchemy.Engine,
) -> None:
    with migrated_database.connect() as connection:
        rows = connection.execute(sqlalchemy.text("SELECT extname FROM pg_extension"))
        present = {row[0] for row in rows}
    assert {"postgis", "pgcrypto", "pg_trgm"}.issubset(present)


def test_all_tables_exist(migrated_database: sqlalchemy.Engine) -> None:
    inspector = sqlalchemy.inspect(migrated_database)
    present = {
        (schema, table)
        for schema in EXPECTED_SCHEMAS
        for table in inspector.get_table_names(schema=schema)
    }
    assert EXPECTED_TABLES.issubset(present)


def test_field_geometry_columns_have_the_right_type_and_srid(
    migrated_database: sqlalchemy.Engine,
) -> None:
    """Reads PostGIS's own catalogue, not our metadata."""
    with migrated_database.connect() as connection:
        rows = connection.execute(
            sqlalchemy.text(
                "SELECT f_geometry_column, type, srid FROM geometry_columns "
                "WHERE f_table_schema = 'farm' AND f_table_name = 'fields'"
            )
        ).all()
        geography_rows = connection.execute(
            sqlalchemy.text(
                "SELECT f_geography_column, type, srid FROM geography_columns "
                "WHERE f_table_schema = 'farm' AND f_table_name = 'fields'"
            )
        ).all()

    # PostGIS's own catalogues disagree on casing here: geometry_columns
    # reports "POLYGON" but geography_columns reports "Point", so the type
    # name is compared case-insensitively. SRID and column name are not.
    geometry_rows = {
        (name, str(geom_type).upper(), srid) for name, geom_type, srid in rows
    }
    geography_rows_normalized = {
        (name, str(geom_type).upper(), srid)
        for name, geom_type, srid in geography_rows
    }
    assert ("boundary", "POLYGON", 4326) in geometry_rows
    assert ("centroid", "POINT", 4326) in geography_rows_normalized


def test_spatial_indexes_are_gist(migrated_database: sqlalchemy.Engine) -> None:
    """A B-tree on a geometry column would be useless for spatial queries."""
    with migrated_database.connect() as connection:
        rows = connection.execute(
            sqlalchemy.text(
                "SELECT i.indexname, i.indexdef FROM pg_indexes i "
                "WHERE i.schemaname = 'farm' AND i.tablename = 'fields'"
            )
        ).all()

    definitions = {row[0]: row[1] for row in rows}
    assert "USING gist" in definitions["ix_farm_fields_boundary_gist"]
    assert "USING gist" in definitions["ix_farm_fields_centroid_gist"]


def test_pending_outbox_index_is_partial(
    migrated_database: sqlalchemy.Engine,
) -> None:
    with migrated_database.connect() as connection:
        definition = connection.execute(
            sqlalchemy.text(
                "SELECT indexdef FROM pg_indexes WHERE schemaname = 'platform' "
                "AND indexname = 'ix_platform_outbox_events_pending'"
            )
        ).scalar_one()
    assert "WHERE" in definition and "PENDING" in definition


def test_role_reference_data_is_seeded(
    migrated_database: sqlalchemy.Engine,
) -> None:
    """user_roles foreign-keys to roles, so the code list must exist."""
    with migrated_database.connect() as connection:
        codes = {
            row[0]
            for row in connection.execute(
                sqlalchemy.text("SELECT code FROM identity.roles")
            )
        }
    assert {"FARMER", "BUYER", "AGRONOMIST", "ADMIN"}.issubset(codes)


def test_migrations_match_the_orm_models(
    migrated_database: sqlalchemy.Engine,
) -> None:
    """`alembic check`: autogenerate must find nothing left to do.

    This is what stops the migration chain and `models.py` from silently
    diverging as new domains land.
    """
    try:
        command.check(_alembic_config())
    except AutogenerateDiffsDetected as exc:
        raise AssertionError(
            f"Migrations have drifted from the SQLAlchemy models: {exc}"
        ) from exc


def test_downgrade_to_base_and_upgrade_again(
    migrated_database: sqlalchemy.Engine,
) -> None:
    """Every revision's downgrade is exercised, then the chain rebuilt.

    Runs last-resort cleanup itself: whatever happens, the database is left
    at head so the rest of the session is unaffected.
    """
    config = _alembic_config()
    try:
        command.downgrade(config, "base")
        with migrated_database.connect() as connection:
            remaining = connection.execute(
                sqlalchemy.text(
                    "SELECT count(*) FROM information_schema.tables "
                    "WHERE table_schema IN ('identity', 'farm', 'platform')"
                )
            ).scalar_one()
        assert remaining == 0
    finally:
        command.upgrade(config, "head")
