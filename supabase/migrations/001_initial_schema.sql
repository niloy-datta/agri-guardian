create table if not exists public.scans (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  disease text not null,
  confidence text,
  severity text,
  field_name text,
  created_at timestamptz not null default now()
);

alter table public.scans enable row level security;

grant select, insert on table public.scans to authenticated;
grant usage, select on sequence public.scans_id_seq to authenticated;

drop policy if exists "Authenticated users can read their own scans"
  on public.scans;
create policy "Authenticated users can read their own scans"
  on public.scans
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Authenticated users can insert their own scans"
  on public.scans;
create policy "Authenticated users can insert their own scans"
  on public.scans
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);
